use std::fmt::Write as _;

/// One corpus test file
///
/// Covers both human created input files and generated snapshot files. The
/// only difference is that snapshot files have non empty `generated` cells.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Document {
    pub sections: Vec<Section>,
}

/// One `##` heading and everything under it
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Section {
    pub name: String,
    pub expectation: Expectation,

    pub elements: Vec<Element>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Element {
    /// Copied verbatim into the snapshot, never parsed
    Prose(String),
    Block(Block),
}

/// One R code cell and the CST and diagnostic cells generated from it
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Block {
    pub source: String,
    pub generated: Vec<Cell>,
}

/// A cell the harness produces, in snapshot files only
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Cell {
    /// The CST view
    Cst(String),
    /// Rendered diagnostics
    Diagnostics(String),
}

/// What a heading's blocks must do when parsed
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub enum Expectation {
    /// Every block must parse with zero diagnostics and no bogus nodes
    #[default]
    Clean,
    /// Every block must produce at least one error diagnostic
    Error,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DocumentError {
    pub line: usize,
    pub message: String,
}

impl std::fmt::Display for DocumentError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "line {}: {}", self.line, self.message)
    }
}

impl std::error::Error for DocumentError {}

impl Expectation {
    fn parse(text: &str, line: usize) -> Result<Self, DocumentError> {
        match text.trim() {
            "error" => Ok(Expectation::Error),
            other => Err(DocumentError {
                line,
                message: format!("unknown marker `{other}`, expected `error`"),
            }),
        }
    }

    fn render(self) -> String {
        match self {
            Expectation::Clean => String::new(),
            Expectation::Error => " [error]".to_string(),
        }
    }
}

impl Section {
    pub fn blocks(&self) -> impl DoubleEndedIterator<Item = &Block> {
        self.elements.iter().filter_map(|element| match element {
            Element::Block(block) => Some(block),
            Element::Prose(_) => None,
        })
    }

    pub fn blocks_mut(&mut self) -> impl DoubleEndedIterator<Item = &mut Block> {
        self.elements
            .iter_mut()
            .filter_map(|element| match element {
                Element::Block(block) => Some(block),
                Element::Prose(_) => None,
            })
    }
}

impl Document {
    pub fn parse(text: &str) -> Result<Document, DocumentError> {
        Parser::new(text).parse()
    }

    pub fn render_snapshot(&self) -> String {
        let mut out = String::new();
        writeln!(out, "<!-- Generated by `xtask accept`. Do not edit. -->").unwrap();

        for section in &self.sections {
            writeln!(out, "\n## {}{}", section.name, section.expectation.render()).unwrap();

            for element in &section.elements {
                match element {
                    Element::Prose(prose) => writeln!(out, "\n{prose}").unwrap(),
                    Element::Block(block) => render_block(&mut out, block),
                }
            }
        }

        out
    }

    /// A comparable shape for this section, to ensure nothing is dropped when
    /// writing the snapshot file
    pub fn shape(&self) -> Vec<(&str, Expectation, usize)> {
        self.sections
            .iter()
            .map(|section| {
                (
                    section.name.as_str(),
                    section.expectation,
                    section.blocks().count(),
                )
            })
            .collect()
    }
}

fn render_block(out: &mut String, block: &Block) {
    render_fence(out, "r", &block.source);

    for cell in &block.generated {
        match cell {
            Cell::Cst(content) => render_fence(out, "cst", content),
            Cell::Diagnostics(content) => render_fence(out, "diagnostics", content),
        }
    }
}

fn render_fence(out: &mut String, language: &str, content: &str) {
    out.push('\n');
    out.push_str("```");
    out.push_str(language);
    out.push('\n');
    out.push_str(content);
    // A cell whose content does not end its line would swallow the fence
    if !content.is_empty() && !content.ends_with('\n') {
        out.push('\n');
    }
    out.push_str("```\n");
}

struct Parser<'src> {
    lines: Vec<&'src str>,
    index: usize,
    sections: Vec<Section>,
    prose: Vec<&'src str>,
}

impl<'src> Parser<'src> {
    fn new(text: &'src str) -> Self {
        // `split_inclusive` keeps each line's terminator, so a file that does
        // not end in a newline is not silently given one
        let lines = text.split_inclusive('\n').collect();

        Self {
            lines,
            index: 0,
            sections: Vec::new(),
            prose: Vec::new(),
        }
    }

    fn parse(mut self) -> Result<Document, DocumentError> {
        while let Some(line) = self.next_line() {
            let trimmed = trim_newline(line);

            if let Some(heading) = trimmed.strip_prefix("## ") {
                self.finish_prose()?;
                let (name, expectation) = parse_heading(heading, self.index)?;
                self.push_section(name, expectation)?;
            } else if let Some(language) = fence_language(trimmed) {
                let content = self.read_fenced_content()?;
                self.push_cell(language, content)?;
            } else if self.sections.is_empty() && trimmed.starts_with("<!--") {
                self.skip_banner(trimmed);
            } else {
                self.prose.push(line);
            }
        }

        self.finish_prose()?;

        for section in &self.sections {
            if section.blocks().next().is_none() {
                return Err(DocumentError {
                    line: self.lines.len(),
                    message: format!("test `{}` has no ```r block", section.name),
                });
            }
        }

        Ok(Document {
            sections: self.sections,
        })
    }

    fn next_line(&mut self) -> Option<&'src str> {
        let line = self.lines.get(self.index).copied();
        self.index += 1;
        line
    }

    fn skip_banner(&mut self, opening: &str) {
        if opening.ends_with("-->") {
            return;
        }

        while let Some(line) = self.next_line() {
            if trim_newline(line).ends_with("-->") {
                return;
            }
        }
    }

    fn read_fenced_content(&mut self) -> Result<String, DocumentError> {
        let opened = self.index;
        let mut content = String::new();

        while let Some(line) = self.next_line() {
            if trim_newline(line) == "```" {
                return Ok(content);
            }
            content.push_str(line);
        }

        Err(DocumentError {
            line: opened,
            message: "unterminated fenced cell".to_string(),
        })
    }

    fn push_section(
        &mut self,
        name: String,
        expectation: Expectation,
    ) -> Result<(), DocumentError> {
        if self.sections.iter().any(|section| section.name == name) {
            return Err(DocumentError {
                line: self.index,
                message: format!(
                    "duplicate test name `{name}`; names must be unique within a file"
                ),
            });
        }

        self.sections.push(Section {
            name,
            expectation,
            elements: Vec::new(),
        });

        Ok(())
    }

    fn push_cell(&mut self, language: &str, content: String) -> Result<(), DocumentError> {
        self.finish_prose()?;

        if language == "r" {
            let block = Block {
                source: content,
                generated: Vec::new(),
            };
            return self.push_element(Element::Block(block));
        }

        let cell = match language {
            "cst" => Cell::Cst(content),
            "diagnostics" => Cell::Diagnostics(content),
            other => {
                return Err(DocumentError {
                    line: self.index,
                    message: format!(
                        "unknown cell language `{other}`, expected `r`, `cst` or `diagnostics`"
                    ),
                });
            }
        };

        self.push_generated(cell)
    }

    fn push_generated(&mut self, cell: Cell) -> Result<(), DocumentError> {
        self.finish_prose()?;

        let line = self.index;
        let block = self
            .sections
            .last_mut()
            .and_then(|section| section.blocks_mut().next_back());

        match block {
            Some(block) => {
                block.generated.push(cell);
                Ok(())
            }
            None => Err(DocumentError {
                line,
                message: "generated cell with no ```r block before it".to_string(),
            }),
        }
    }

    fn push_element(&mut self, element: Element) -> Result<(), DocumentError> {
        match self.sections.last_mut() {
            Some(section) => {
                section.elements.push(element);
                Ok(())
            }
            None => Err(DocumentError {
                line: self.index,
                message: "content before the first `## ` heading".to_string(),
            }),
        }
    }

    /// Flushes accumulated prose, dropping its boundary blank lines
    ///
    /// The trim is what makes rendering idempotent: loosely spaced input
    /// converges after one `just accept` instead of gaining a blank line on
    /// every pass.
    fn finish_prose(&mut self) -> Result<(), DocumentError> {
        let lines = std::mem::take(&mut self.prose);
        let prose = lines.concat();
        let prose = prose.trim_matches('\n');

        if prose.is_empty() {
            return Ok(());
        }

        self.push_element(Element::Prose(prose.to_string()))
    }
}

fn parse_heading(heading: &str, line: usize) -> Result<(String, Expectation), DocumentError> {
    let heading = heading.trim();

    // The marker is the trailing bracketed group, so a name may itself contain
    // brackets — `Unsupported Subset2 With `]]` Over Multiple Lines` does
    let Some(open) = heading.strip_suffix(']').and_then(|rest| rest.rfind('[')) else {
        return Ok((heading.to_string(), Expectation::default()));
    };

    let inside = &heading[open + 1..heading.len() - 1];
    if inside.contains('[') || inside.contains(']') {
        return Ok((heading.to_string(), Expectation::default()));
    }

    let expectation = Expectation::parse(inside, line)?;
    Ok((heading[..open].trim().to_string(), expectation))
}

fn fence_language(line: &str) -> Option<&str> {
    let language = line.strip_prefix("```")?;

    if language.is_empty() || language.contains(' ') {
        None
    } else {
        Some(language)
    }
}

fn trim_newline(line: &str) -> &str {
    line.trim_end_matches('\n').trim_end_matches('\r')
}

#[cfg(test)]
mod tests {
    use super::*;

    fn document(text: &str) -> Document {
        Document::parse(text).expect("the document parses")
    }

    fn error(text: &str) -> String {
        Document::parse(text)
            .expect_err("the document is rejected")
            .message
    }

    const INPUT: &str = "\
## Numbers

```r
1
```

## Dollar [error]

Why this test exists.

```r
a$
```

```r
b$
```
";

    #[test]
    fn parses_headings_markers_and_blocks() {
        let document = document(INPUT);

        assert_eq!(
            document.shape(),
            vec![
                ("Numbers", Expectation::Clean, 1),
                ("Dollar", Expectation::Error, 2),
            ]
        );

        let sources: Vec<_> = document.sections[1]
            .blocks()
            .map(|block| block.source.as_str())
            .collect();

        assert_eq!(sources, vec!["a$\n", "b$\n"]);
    }

    /// Prose keeps its place in the element sequence, so rendering can put each
    /// block's cells beside it
    #[test]
    fn prose_interleaves_with_blocks() {
        let document = document(INPUT);

        assert!(matches!(
            document.sections[1].elements.as_slice(),
            [
                Element::Prose(prose),
                Element::Block(_),
                Element::Block(_)
            ] if prose == "Why this test exists."
        ));
    }

    /// Textual idempotence is the contract, since CI regenerates and asserts a
    /// clean tree. A cell whose content does not end its line gains a newline, so
    /// the structural round-trip holds only for content that already ends in one.
    #[test]
    fn round_trips_through_a_snapshot() {
        let mut document = document(INPUT);
        document.sections[0].blocks_mut().next().unwrap().generated =
            vec![Cell::Cst("RRoot { }\n".to_string())];
        document.sections[1].blocks_mut().for_each(|block| {
            block.generated = vec![
                Cell::Cst("RBogusExpression { }\n".to_string()),
                Cell::Diagnostics("error\n".to_string()),
            ]
        });

        let rendered = document.render_snapshot();
        assert_eq!(Document::parse(&rendered).unwrap(), document);
        assert_eq!(
            Document::parse(&rendered).unwrap().render_snapshot(),
            rendered
        );
    }

    /// Loosely spaced input must converge after one pass rather than gaining a
    /// blank line on every one
    #[test]
    fn rendering_is_idempotent_over_prose_spacing() {
        let loose = "## A\n\n\n\nSpaced out.\n\n\n\n```r\n1\n```\n";
        let rendered = document(loose).render_snapshot();

        assert_eq!(document(&rendered).render_snapshot(), rendered);
    }

    #[test]
    fn an_empty_block_survives() {
        let document = document("## A\n\n```r\n```\n");
        assert_eq!(document.sections[0].blocks().next().unwrap().source, "");

        let rendered = document.render_snapshot();
        assert_eq!(Document::parse(&rendered).unwrap(), document);
    }

    /// A name may hold brackets of its own; only a trailing group is a marker
    #[test]
    fn markers_are_the_trailing_bracket_group() {
        let document = document("## Subset2 With `]]` (#177) [error]\n\n```r\n1\n```\n");

        assert_eq!(
            document.shape(),
            vec![("Subset2 With `]]` (#177)", Expectation::Error, 1)]
        );
    }

    #[test]
    fn rejects_content_before_the_first_heading() {
        assert!(error("Stray prose.\n\n## A\n\n```r\n1\n```\n").contains("before the first"));
    }

    #[test]
    fn rejects_a_heading_with_no_block() {
        assert!(error("## A\n\nJust prose.\n").contains("no ```r block"));
    }

    #[test]
    fn rejects_a_duplicate_name() {
        let text = "## A\n\n```r\n1\n```\n\n## A\n\n```r\n2\n```\n";
        assert!(error(text).contains("duplicate test name"));
    }

    #[test]
    fn rejects_an_unknown_marker() {
        assert!(error("## A [wip]\n\n```r\n1\n```\n").contains("unknown marker"));
    }

    #[test]
    fn rejects_an_unterminated_cell() {
        assert!(error("## A\n\n```r\n1\n").contains("unterminated"));
    }
}
